#!/bin/sh
set -eu

CC=${CC:-cc}
READELF=${READELF:-readelf}
lib= out= note=
incdirs= includes=
uinttypes="bool _Bool uint8_t uint16_t uint32_t uint64_t unsigned size_t ssize_t sf_count_t uintptr_t intptr_t"

while [ "$#" -gt 0 ]; do
	case "$1" in
		--lib) lib=$2; shift 2;;
		--out) out=$2; shift 2;;
		--note) note=$2; shift 2;;
		--include) includes="$includes $2"; shift 2;;
		--include-dir) incdirs="$incdirs -I$2"; shift 2;;
		--uint-type) uinttypes="$uinttypes $2"; shift 2;;
		--readelf) READELF=$2; shift 2;;
		*) echo "unknown option: $1" >&2; exit 1;;
	esac
done

[ -n "$lib" ] && [ -n "$out" ] && [ -n "$includes" ] || {
	echo "usage: $0 --lib PATH --out PATH --include-dir DIR --include HEADER [...]" >&2
	exit 1
}

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

{
	for h in $includes; do
		echo "#include <$h>"
	done
} > "$tmp/inc.c"

$CC -aux-info "$tmp/aux" -fsyntax-only $incdirs "$tmp/inc.c"
$CC -E -P $incdirs "$tmp/inc.c" > "$tmp/pp"

# extern prototypes produced by -aux-info, e.g.:
# /* /usr/include/systemd/sd-bus.h:45:NC */ extern int sd_bus_open (sd_bus **);
sed -n 's@^/\*.*\*/ @@p' "$tmp/aux" |
awk '
	$1 == "extern" {
		line = $0
		sub(/^extern[ \t]+/, "", line)
		if (!match(line, /[A-Za-z_][A-Za-z0-9_]* \(/))
			next
		name = substr(line, RSTART, RLENGTH - 2)
		ret = substr(line, 1, RSTART - 1)
		sub(/[ \t]+$/, "", ret)
		print name "\t" ret
	}' | LC_ALL=C sort -u > "$tmp/protos"

# pointer typedefs, e.g. typedef int (*sd_bus_message_handler_t)(...);
tr '\n' ' ' < "$tmp/pp" |
grep -oE 'typedef[^;{}]*\(\*[[:space:]]*[A-Za-z_][A-Za-z0-9_]*[[:space:]]*\)' |
sed -E 's/.*\(\*[[:space:]]*([A-Za-z_][A-Za-z0-9_]*)[[:space:]]*\)/\1/' |
LC_ALL=C sort -u > "$tmp/ptr"
# object pointer typedefs, e.g. typedef struct foo *foo_t;
tr '\n' ' ' < "$tmp/pp" |
grep -oE 'typedef[^;{}]*\*[[:space:]]*[A-Za-z_][A-Za-z0-9_]*[[:space:]]*;' |
sed -E 's/.*\*[[:space:]]*([A-Za-z_][A-Za-z0-9_]*)[[:space:]]*;/\1/' |
LC_ALL=C sort -u >> "$tmp/ptr"

# enum typedefs, so enum returns get 0 instead of -ENOSYS
tr '\n' ' ' < "$tmp/pp" |
grep -oE 'typedef enum[^}]*}[[:space:]]*[A-Za-z_][A-Za-z0-9_]*[[:space:]]*;' |
sed -E 's/.*}[[:space:]]*([A-Za-z_][A-Za-z0-9_]*)[[:space:]]*;/\1/' |
LC_ALL=C sort -u > "$tmp/enum"

$READELF --dyn-syms -W "$lib" | awk '
	$1 == "Num:" || NF < 8 { next }
	$4 ~ /^(FUNC|IFUNC|OBJECT)$/ && $(NF-1) != "UND" && $(NF-1) != "ABS" && index($NF, "@@") > 0 {
		split($NF, a, "@@")
		print a[1] "\t" a[2] "\t" $4 "\t" $3
	}' | LC_ALL=C sort -u > "$tmp/exports"

awk -F'\t' -v uinttypes="$uinttypes" '
	BEGIN {
		n = split(uinttypes, t, /[ \t]+/)
		for (i = 1; i <= n; i++)
			if (t[i] != "")
				u[t[i]] = 1
	}
	FILENAME == ARGV[1] { proto[$1] = $2; next }
	FILENAME == ARGV[2] { ptr[$1] = 1; next }
	FILENAME == ARGV[3] { enu[$1] = 1; next }
	{
		name = $1; ver = $2; typ = $3; size = $4
		if (typ == "OBJECT") {
			cls = "data:" size
		} else {
			ret = proto[name]
			if (ret == "") {
				missing[name] = 1
				ret = "int"
			}
			cls = classify(ret)
		}
		print name "\t" ver "\t" typ "\t" cls
	}
	function classify(r,   n, a, i) {
		if (index(r, "*") > 0)
			return "ptr"
		if (r ~ /(^|[^A-Za-z0-9_])void([^A-Za-z0-9_]|$)/)
			return "void"
		if (index(r, "sd_id128_t") > 0)
			return "id128"
		if (r ~ /(^|[^A-Za-z0-9_])(double|float)([^A-Za-z0-9_]|$)/)
			return "fp"
		n = split(r, a, /[^A-Za-z0-9_]+/)
		for (i = 1; i <= n; i++)
			if (a[i] in u)
				return "uint"
		if (n > 0 && (a[n] in ptr))
			return "ptr"
		if (n > 0 && (a[n] in enu))
			return "uint"
		return "int"
	}
	END {
		for (name in missing)
			print "warning: no prototype for " name > "/dev/stderr"
	}
' "$tmp/protos" "$tmp/ptr" "$tmp/enum" "$tmp/exports" > "$tmp/manifest"

{
	echo "# generated by tools/gen-manifest.sh -- do not edit by hand"
	[ -z "$note" ] || echo "# source: $note"
	printf '# name\tversion\ttype\tclass\n'
	cat "$tmp/manifest"
} > "$out"

echo "$out: $(grep -vc '^#' "$out") symbols" >&2
