#!/bin/sh
# Generate the C file and linker version script for a dummy library.
#
# The manifest is the TSV produced by gen-manifest.sh. Every symbol is
# turned into a placeholder with a safe return value, except the symbols
# listed in the custom file, which are implemented by hand in overrides.c.
set -eu

manifest= custom= outc= outmap=
while [ "$#" -gt 0 ]; do
	case "$1" in
		--manifest) manifest=$2; shift 2;;
		--custom) custom=$2; shift 2;;
		--out-c) outc=$2; shift 2;;
		--out-map) outmap=$2; shift 2;;
		*) echo "unknown option: $1" >&2; exit 1;;
	esac
done

[ -n "$manifest" ] && [ -n "$outc" ] && [ -n "$outmap" ] || {
	echo "usage: $0 --manifest FILE --custom FILE --out-c FILE --out-map FILE" >&2
	exit 1
}

if [ -n "$custom" ]; then
	missing=$(awk -F'\t' '
		FILENAME == ARGV[1] {
			if ($0 !~ /^#/ && NF)
				custom[$1] = 1
			next
		}
		!/^#/ && NF { seen[$1] = 1 }
		END { for (n in custom) if (!(n in seen)) print n }
	' "$custom" "$manifest")
	if [ -n "$missing" ]; then
		echo "custom symbols not in manifest:" >&2
		printf '%s\n' "$missing" | sed 's/^/  /' >&2
		exit 1
	fi
fi

{
	echo "/* generated by tools/gen-stub.sh -- do not edit */"
	echo "#include <errno.h>"
	echo "#include <stdint.h>"
	echo "#include <stddef.h>"
	echo
	echo "struct stub_id128 { uint64_t q[2]; };"
	echo
	awk -F'\t' -v custom="$custom" '
		BEGIN {
			if (custom != "") {
				while ((getline line < custom) > 0)
					if (line !~ /^#/ && line != "")
						c[line] = 1
				close(custom)
			}
		}
		!/^#/ && NF {
			name = $1; cls = $4
			if (name in c)
				next
			if (cls == "int")
				print "int64_t " name "(void) { return (int64_t)-ENOSYS; }"
			else if (cls == "uint")
				print "uint64_t " name "(void) { return 0; }"
			else if (cls == "ptr")
				print "void *" name "(void) { return NULL; }"
			else if (cls == "void")
				print "void " name "(void) { }"
			else if (cls == "fp")
				print "double " name "(void) { return 0.0; }"
			else if (cls == "id128")
				print "struct stub_id128 " name "(void) { struct stub_id128 r = { { 0, 0 } }; return r; }"
			else if (cls ~ /^data:/) {
				split(cls, a, ":")
				size = a[2] + 0
				if (size < 1)
					size = 1
				print "unsigned char " name "[" size "];"
			} else {
				print "unknown class " cls " for " name > "/dev/stderr"
				bad = 1
			}
		}
		END { if (bad) exit 1 }
	' "$manifest"
} > "$outc"

awk -F'\t' '!/^#/ && NF {
		v = $2
		n = v
		sub(/.*_/, "", n)
		if (n !~ /^[0-9]+$/)
			n = 0
		print n "\t" v "\t" $1
	}' "$manifest" |
LC_ALL=C sort -k1,1n -k2,2 -k3,3 |
cut -f2- |
awk -F'\t' '
	function close_node() {
		print "\tlocal: *;"
		if (last != "")
			print "} " last ";"
		else
			print "};"
		last = cur
	}
	{
		if ($1 != cur) {
			if (cur != "")
				close_node()
			cur = $1
			print cur " {"
			print "\tglobal:"
		}
		print "\t\t" $2 ";"
	}
	END { if (cur != "") close_node() }
' > "$outmap"

echo "$outc: $(grep -vc '^#' "$manifest") symbols" >&2
